#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

const int MAXN = 100;
int a[MAXN];

int main() {
    fast();

    int n; cin >> n;
    int dem, ans = 0;
    for (int i = 1; i <= n; i++) cin >> a[i];
    for (int i = 1; i <= n; i++) {
        for (int j = i; j <= n; j++) {
            cout << a[i] << " " << a[j] << " ";
            if (a[i] < a[j]) dem++;
        }
        if (dem == n-i) ans++;
    }
    cout << endl;
    cout << ans;

    return 0;
}












