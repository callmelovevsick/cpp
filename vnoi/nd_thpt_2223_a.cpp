#include <bits/stdc++.h>
#include <string>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

long long s(int n) {
    string tmp = to_string(n);
    long long tong = 0;
    for (int i = 0; i < tmp.size(); i++) tong += tmp[i] - '0';
    return tong;
}

bool check(int n) {
    if (s(n) % 10 == 9) return true;
    else return false;
}

int main() {
    fast();
    in("sodep");
    out("sodep");

    long long n; cin >> n;
    cout << check(n);

    return 0;
}


























