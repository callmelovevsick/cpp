#include <bits/stdc++.h>
using namespace std;

#define LucKhanhVan ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

int n;
vector<int> a(n);
vector<int> pref(n+1, 0);

bool check(int n) {
    if (n <= 1) return false;
    if (n <= 3) return true;
    for (int i = 5; i <= n; i += 6) {
        if (n % i == 0 || n % (i+1) == 0) return false;
    }
    return true;
}

void yeukv() {
    int u, v; cin >> u >> v;
    if (check(pref[v] - pref[u-1])) cout << 1;
    else cout << 0;
}

int main() {
    LucKhanhVan;

    int t; cin >> n >> t;
    for (int i = 0; i < n; i++) {
        cin >> a[i];
        pref[i] = pref[i+1] + a[i];
    }
    while (t--) {
        yeukv();
    }

    return 0;
}












