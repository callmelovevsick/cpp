#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

int main() {
    fast();
    in("THUGON");
    out("THUGON");

    string s; 
    while (cin >> s) {
        int dem = 0;
        char prev_c = s[0];
        for (int i = 0; i < s.size(); i++) {
            if (prev_c == s[i]) {
                dem++;
            } else {
                if (dem == 1) cout << prev_c;
                else cout << dem << prev_c;
                dem = 1;
                prev_c = s[i];
            }
        }
        if (dem == 1) cout << prev_c;
        else cout << dem << prev_c;
        cout << "\n";
    }

    return 0;
}


























