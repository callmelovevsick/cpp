#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

const int MAXN = 1e6+5;
int a[MAXN];

bool prime(int n) {
    if (n <= 1) return false;
    if (n <= 3) return true;
    if (n % 2 == 0 || n % 3 == 0) return false;
    for (int i = 5; i*i <= n; i += 6) {
        if (n % i == 0 || n % (i+1) == 0) return false;
    }
    return true;
}

int main() {
    fast();
    in("CAU3");
    out("CAU3");

    int n; cin >> n;
    vector<int> v;
    for (int i = 0; i < n; i++) {
        cin >> a[i];
        if (prime(a[i])) v.push_back(a[i]);
    }
    sort(v.begin(), v.end());
    for (auto &x : v) cout << x << " ";

    return 0;
}


























