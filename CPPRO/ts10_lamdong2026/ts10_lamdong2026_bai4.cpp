#include <algorithm>
#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

int main() {
    fast();
    in("CAU4");
    out("CAU4");

    int n, m; cin >> n >> m;
    vector<long long> a(n);
    for (int i = 0; i < n; i++) cin >> a[i];
    sort(a.begin(), a.end());
    a.erase(unique(a.begin(), a.end()), a.end());
    for (int j = 0; j < m; j++) {
        long long b; cin >> b;
        int count = lower_bound(a.begin(), a.end(), b) - a.begin();
        long long ans = (b-1) - count;
        cout << ans << "\n";
    }

    return 0;
}












