#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);
#define int long long

int n, x, q;
int ans = 0;

signed main() {
    fast();

    cin >> n >> x >> q;
    vector<int> a(n+1);
    vector<int> pref(n+1, 0);
    for (int i = 1; i <= n; i++) {
        cin >> a[i];
        pref[i] = pref[i-1] + a[i];
    }
    while (q--) {
        int u, v; cin >> u >> v;
        if (pref[v] - pref[u-1] < x) ans++; 
    }
    cout << ans;

    return 0;
}


























