#include <bits/stdc++.h>
using namespace std;

#define LucKhanhVan ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

int main() {
    LucKhanhVan;

    int n; cin >> n;
    vector<int> a(n);
    vector<int> pref(n+1, 0);
    for (int i = 0; i < n; i++) {
        cin >> a[i];
        if (a[i] == 0) a[i] -= 1;
    }
    map <long long, int> mp;
    int ans = 0;
    mp[pref[0]] = 0;
    for (int i = 0; i < n; i++) {
        pref[i+1] = pref[i] + a[i];
        if (mp.count(pref[i+1])) ans = max(ans, (int)((a.begin() + i) - (a.begin() + mp[pref[i+1]]) + 1));
        else mp[pref[i+1]] = i + 1;
    }    
    cout << ans;

    return 0;
}












