#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

int main() {
    fast();

    int n; cin >> n;
    vector<long long> a(n);
    long long sum = 0;
    for (int i = 0; i < n; i++) { 
        cin >> a[i];
        sum += a[i];
    }
    if (sum % 2 != 0) {
        cout << 0;
        return 0;
    }
    long long tar = sum / 2;
    long long curr = 0;
    int count = 0;
    for (int i = 0; i < n-1; i++) {
        curr += a[i];
        if (curr == tar) count++;
    }
    cout << count;

    return 0;
}












