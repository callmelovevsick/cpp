#include <bits/stdc++.h>
using namespace std;

#define fast() ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

int main() {
    fast();

    int n; cin >> n;
    vector<long long> a(n+1);
    vector<long long> pref(n+1, 0);
    for (int i = 1; i <= n; i++) {
        cin >> a[i];
        pref[i] = pref[i-1] + a[i];
    }    
    long long maxs = -1e18;
    long long mins = 0;
    for (int r = 1; r <= n; r++) {
        long long curr = pref[r] - mins;
        if (curr > maxs) maxs = curr;
        if (pref[r] < mins) mins = pref[r];
    }
    cout << maxs;

    return 0;
}




















