#include <bits/stdc++.h>
using namespace std;

#define LucKhanhVan ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

const int MAXN = 1e5;
int pref[MAXN];

int main() {
    LucKhanhVan;

    int n, q; cin >> n >> q;
    while (q--) {
        int t, l, r, x; cin >> t >> l >> r >> x;
        if (t == 1) {
            pref[l] += x;
            pref[r+1] -= x;
        }
        if (t == 2) {
            pref[l] -= x;
            pref[r+1] += x;
        }
    }
    int s = 0;
    for (int i = 1; i <= n; i++) {
        s += pref[i];
        cout << s << " ";
    }

    return 0;
}












