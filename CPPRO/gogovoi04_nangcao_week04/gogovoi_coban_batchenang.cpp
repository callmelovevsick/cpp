#include <bits/stdc++.h>
using namespace std;

#define LucKhanhVan ios::sync_with_stdio(false); cin.tie(0);
#define in(file) freopen(file ".inp", "r", stdin);
#define out(file) freopen(file ".out", "w", stdout);

const int MAXN = 60000;
int pref[MAXN+5];

int main() {
    LucKhanhVan;

    int n; cin >> n;
    for (int i = 0; i < n; i++) {
        int l, r; cin >> l >> r;
        pref[l]++;
        pref[r]--;
    }
    int ans, len, curr = 0;
    for (int i = 0; i <= MAXN; i++) {
        curr += pref[i];
        if (curr > 0) {
            len++;
        } else {
            ans = max(ans, len);
            len = 0;
        }
    }
    cout << ans;

    return 0;
}












